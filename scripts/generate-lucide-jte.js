const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");

// Java keywords cannot become facade method names. Keep canonical SVG classes.
const JAVA_RESERVED = new Set((
  "abstract assert boolean break byte case catch char class const continue default " +
  "do double else enum extends final finally float for goto if implements import " +
  "instanceof int interface long native new package private protected public return " +
  "short static strictfp super switch synchronized this throw throws transient try " +
  "void volatile while true false null _"
).split(" "));

function templateName(fileName) {
  const camel = fileName.replace(/-([a-zA-Z0-9])/g, (_, letter) => letter.toUpperCase());
  const name = JAVA_RESERVED.has(camel) ? `${camel}Icon` : camel;
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) {
    throw new Error(`Icon filename cannot become a Java method: ${fileName}`);
  }
  return name;
}

function canonicalFiles(source) {
  const files = [...source.matchAll(/from ['"]\.\/icons\/([^'"]+)\.mjs['"];?/g)]
    .map((match) => match[1]);
  if (files.length === 0) throw new Error("No canonical icon exports found in Lucide package");
  return [...new Set(files)].sort();
}

function escapeAttribute(value) {
  return String(value).replaceAll("&", "&amp;").replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

function renderNode([tag, attributes]) {
  if (!new Set(["path", "circle", "ellipse", "line", "polyline", "polygon", "rect"]).has(tag)) {
    throw new Error(`Unexpected SVG node: ${tag}`);
  }
  const attrs = Object.entries(attributes).map(([name, value]) => {
    if (!/^[a-zA-Z][a-zA-Z0-9:-]*$/.test(name)) throw new Error(`Invalid SVG attribute: ${name}`);
    return `${name}="${escapeAttribute(value)}"`;
  });
  return attrs.join(" ").length <= 80
    ? `  <${tag} ${attrs.join(" ")} />`
    : `  <${tag}\n${attrs.map((attr) => `    ${attr}`).join("\n")}\n  />`;
}

function renderTemplate(stub, values) {
  return stub.replace(/\{\{([A-Z_]+)\}\}/g, (_, token) => {
    if (!Object.hasOwn(values, token)) throw new Error(`Missing template value for ${token}`);
    return values[token];
  });
}

function renderStaticFacade(names, version) {
  const methods = [...names].map((name) => `    public static Icon ${name}() {
        return ${name}(IconOptions.DEFAULT);
    }

    public static Icon ${name}(IconOptions options) {
        return new Icon(INSTANCE::${name}, options);
    }
`).join("\n");
  return `// Generated from Lucide ${version} by npm run generate:lucide-jte. Do not edit.
package io.github.sgruendel.lucide.jte;

import static io.github.sgruendel.lucide.jte.StaticLucideIcon.INSTANCE;

/** Static helpers returning immutable icons with fluent styling methods. */
public final class LucideIcons {
    private LucideIcons() {
    }

${methods}}
`;
}

async function generate(root, check = false) {
  const packageDir = path.join(root, "node_modules", "lucide");
  if (!fs.existsSync(path.join(packageDir, "package.json"))) {
    throw new Error("Lucide package is missing. Run npm ci first.");
  }
  const { version } = JSON.parse(fs.readFileSync(path.join(packageDir, "package.json"), "utf8"));
  const esm = path.join(packageDir, "dist", "esm");
  const icons = canonicalFiles(fs.readFileSync(path.join(esm, "iconsAndAliases.mjs"), "utf8"));
  const stub = fs.readFileSync(path.join(root, "scripts", "templates", "lucide-icon.jte"), "utf8");
  const expected = new Map();
  const names = new Set();
  for (const file of icons) {
    const name = templateName(file);
    if (names.has(name)) throw new Error(`Icon template name collision: ${name}`);
    names.add(name);
    const { default: nodes } = await import(pathToFileURL(path.join(esm, "icons", `${file}.mjs`)).href);
    if (!Array.isArray(nodes) || nodes.length === 0) throw new Error(`Invalid icon nodes: ${file}`);
    expected.set(`src/main/jte/${name}.jte`, renderTemplate(stub, {
      ICON_FILE_NAME: file, LUCIDE_VERSION: version, CHILDREN: nodes.map(renderNode).join("\n"),
    }));
  }
  expected.set("src/main/java/io/github/sgruendel/lucide/jte/LucideIcons.java",
    renderStaticFacade(names, version));
  expected.set("src/main/resources/META-INF/lucide-jte.properties",
    `# Generated by npm run generate:lucide-jte\nlucide.version=${version}\nicon.count=${icons.length}\n`);
  expected.set("THIRD-PARTY-LICENSES/LUCIDE.txt", fs.readFileSync(path.join(packageDir, "LICENSE"), "utf8"));

  const output = path.join(root, "src", "main", "jte");
  const stale = fs.existsSync(output)
    ? fs.readdirSync(output).filter((file) => file.endsWith(".jte") && !expected.has(`src/main/jte/${file}`))
    : [];
  const differences = [];
  for (const [relative, content] of expected) {
    const target = path.join(root, relative);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content) differences.push(relative);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
    }
  }
  if (check && (differences.length || stale.length)) {
    throw new Error(`Generated files are out of date (${differences.length} missing/changed, ${stale.length} stale). Run npm run generate:lucide-jte.`);
  }
  if (!check) for (const file of stale) fs.unlinkSync(path.join(output, file));
  console.log(`${check ? "Verified" : "Generated"} ${icons.length} canonical icons from Lucide ${version}.`);
  return icons.length;
}

module.exports = { templateName, canonicalFiles, escapeAttribute, renderNode, renderTemplate, generate };

if (require.main === module) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check")) {
    console.error("Usage: node scripts/generate-lucide-jte.js [--check]");
    process.exitCode = 1;
  } else {
    generate(path.resolve(__dirname, ".."), args.includes("--check")).catch((error) => {
      console.error(error.message);
      process.exitCode = 1;
    });
  }
}
